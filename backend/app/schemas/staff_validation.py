"""
backend/app/schemas/staff_validation.py

Feature 36: Schemas for Counsellor Ground-Truth Validation Workspaces.
Covers C1 Affective State Label Confirmation and C4 Intervention Appropriateness Rating.
"""

from datetime import datetime
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field

from app.models.validation import C1DistressLabel


# ── C1 Queue & Labelling Schemas ──────────────────────────────────────────────

class C1QueueMessageItem(BaseModel):
    """Scrubbed textual evidence presented to the counsellor for weekly distress labelling."""
    message_id: str
    source_type: str
    timestamp: datetime
    clean_text: str


class C1QueueItemResponse(BaseModel):
    """Weekly affective observation unit queued for blind counsellor labelling."""
    item_id: str = Field(..., description="Unique deterministic identifier (pid:course:week)")
    pid: str
    course_id: str
    week_index: int
    message_count: int
    messages: List[C1QueueMessageItem]
    blind: bool = True
    model_top_class: Optional[str] = None
    model_top_score: Optional[float] = None


class C1LabelCreateRequest(BaseModel):
    """Payload submitted by counsellor to confirm or correct C1 distress class."""
    pid: str = Field(..., description="Target student PID (STU_xxxxxxxx)")
    course_id: str = Field(..., description="Course identifier")
    week_index: int = Field(..., ge=0, description="Academic week index")
    counsellor_label: C1DistressLabel = Field(
        ...,
        description="Expert-identified distress class (or 'none')",
    )
    confidence: int = Field(
        ...,
        ge=1,
        le=3,
        description="Rating certainty (1=Low, 2=Medium, 3=High)",
    )


class C1LabelCreateResponse(BaseModel):
    """Response returned upon saving C1 label, revealing model prediction for comparison."""
    label_id: str
    pid: str
    course_id: str
    week_index: int
    counsellor_label: str
    confidence: int
    model_top_class: str
    model_top_score: float
    agreement: bool
    message: str = "Label recorded successfully"


class C1ClassMetricsItem(BaseModel):
    """Per-class diagnostic performance metrics."""
    precision: float
    recall: float
    f1: float
    support: int


class C1SummaryResponse(BaseModel):
    """Aggregate statistical evaluation of C1 Affective State Detection against ground truth."""
    n_items: int
    agreement_pct: float
    cohen_kappa: float
    cohen_kappa_band: str
    confusion_matrix: Dict[str, Dict[str, int]]
    per_class_metrics: Dict[str, C1ClassMetricsItem]
    macro_f1: float
    inter_rater_kappa: Optional[float] = None
    inter_rater_band: Optional[str] = None


# ── C4 Queue & Rating Schemas ─────────────────────────────────────────────────

class C4CandidateItem(BaseModel):
    """Ranked intervention candidate option generated by Component 4."""
    rank: int
    intervention_type: str
    label: str
    student_label: str
    delivery_module: str
    suitability_score: float
    rationale: str


class C4QueueItemResponse(BaseModel):
    """Unrated recommendation batch queued for expert appropriateness assessment."""
    recommendation_id: str
    pid: str
    course_id: Optional[str] = None
    week_index: int
    risk_tier: Optional[str] = None
    candidates: List[C4CandidateItem]
    created_at: datetime


class C4RatingCreateRequest(BaseModel):
    """Payload submitted by counsellor rating recommendation appropriateness and ranking."""
    recommendation_id: str = Field(..., description="UUID of the recommendation")
    appropriateness: int = Field(
        ...,
        ge=1,
        le=5,
        description="1-5 Likert scale appropriateness score",
    )
    suitable_ranks: List[int] = Field(
        default_factory=list,
        description="1-based candidate ranks deemed suitable (e.g. [1, 2])",
    )
    top1_acceptable: bool = Field(
        ...,
        description="Whether top-1 choice is acceptable for dispatch",
    )
    comment: Optional[str] = Field(
        default=None,
        max_length=500,
        description="Optional confidential qualitative rationale",
    )


class C4RatingCreateResponse(BaseModel):
    """Response returned upon recording recommendation appropriateness rating."""
    rating_id: str
    recommendation_id: str
    appropriateness: int
    suitable_ranks: List[int]
    top1_acceptable: bool
    message: str = "Recommendation rating recorded successfully"


class C4SummaryResponse(BaseModel):
    """Aggregate evaluation metrics for Component 4 adaptive recommendation ranking."""
    n: int = Field(..., description="Total rated recommendations count")
    mean_appropriateness: float = Field(..., description="Mean Likert rating (1-5)")
    precision_at_1: float = Field(..., description="Mean Precision@1 across ratings")
    precision_at_3: float = Field(..., description="Mean Precision@3 across ratings")
    ndcg_at_3: float = Field(..., description="Mean Normalized Discounted Cumulative Gain at 3")
    top1_acceptable_rate: float = Field(..., description="Proportion where top-1 choice is acceptable")
    acceptance_mix: Dict[str, Any] = Field(
        default_factory=dict,
        description="Operational review acceptance breakdown from recommendation_reviews",
    )


# ── Administrative Export Schemas ─────────────────────────────────────────────

class ValidationExportC1LabelRow(BaseModel):
    """Pseudonymous C1 ground-truth label row."""
    label_id: str
    pid: str
    course_id: str
    week_index: int
    model_top_class: str
    model_top_score: float
    counsellor_label: str
    confidence: int
    reviewer_id: str
    created_at: datetime


class ValidationExportC4RatingRow(BaseModel):
    """Pseudonymous C4 ranking evaluation rating row. Comments are strictly excluded."""
    recommendation_id: str
    reviewer_id: str
    appropriateness: int
    suitable_ranks: List[int]
    top1_acceptable: bool
    created_at: datetime


class ValidationExportResponse(BaseModel):
    """Administrative export of ground-truth validation datasets for research evaluation."""
    schema_version: Literal["validation-export-1.0"] = Field(
        default="validation-export-1.0",
        alias="schema",
    )
    exported_at: datetime
    c1_labels_count: int
    c4_ratings_count: int
    c1_labels: List[ValidationExportC1LabelRow]
    c4_ratings: List[ValidationExportC4RatingRow]

    model_config = {
        "populate_by_name": True,
    }
